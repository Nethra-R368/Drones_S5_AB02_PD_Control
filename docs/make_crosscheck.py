#!/usr/bin/env python3
"""
make_crosscheck.py - builds the Python-vs-MATLAB cross-check table of the complete documentation.

Reads   docs/results/metrics.json        (written by paper_reproduction.py)
        toy_model/results_log.txt        (written by toy_model/run_all.m in MATLAB)
Writes  docs/complete_documentation/sections/03b_crosscheck_table.tex

    python3 docs/make_crosscheck.py      # then recompile AB02_Drone_Documentation.tex

If the MATLAB log does not exist yet, the table is written with the Python column only and says so.
"""
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
LOG = os.path.join(ROOT, "toy_model", "results_log.txt")
OUT = os.path.join(HERE, "complete_documentation", "sections", "03b_crosscheck_table.tex")
M = json.load(open(os.path.join(HERE, "results", "metrics.json")))


def matlab_rows():
    """Returns {label: [values]} for the step-6 lines of the MATLAB log, or None."""
    if not os.path.exists(LOG):
        return None
    txt = open(LOG, encoding="utf-8", errors="replace").read()
    s6 = txt[txt.find("STEP 6"):]
    rows = {}
    for lab in ("Ts=15", "Ts=10", "paper", "symmetric", "pd"):
        m = re.search(r"\[OUT\]\s+" + re.escape(lab) + r"\s.*?\n\s+=\s+\[([^\]]+)\]", s6)
        if m:
            rows[lab] = [float(v) for v in m.group(1).split()]
    return rows or None


def f(x, d=3):
    return f"{x:.{d}f}"


mat = matlab_rows()
p1, p2 = M["part1"], M["part2"]
# (label, python value, matlab index in its printed vector, matlab key, digits)
lines = []
for Ts in ("15", "10"):
    py = p1[f"Ts={Ts}"]
    for name, key, idx, d in (("$\\max|\\varepsilon_1|$", "eps1_max", 0, 3), ("$\\max|\\varepsilon_2|$", "eps2_max", 1, 3),
                              ("time outside $\\rho_q$ (\\%)", "viol_q", 2, 1), ("time outside $\\rho_\\omega$ (\\%)", "viol_w", 3, 1),
                              ("settling time (s)", "settle", 4, 2)):
        mv = mat.get(f"Ts={Ts}") if mat else None
        lines.append((f"Part 1, $T_s={Ts}$\\,s", name, f(py[key], d), f(mv[idx], d) if mv else "--"))
for mode, mkey in (("constrained", "paper"), ("symmetric", "symmetric"), ("pd", "pd")):
    py = p2[mode]
    lab = {"constrained": "Part 2, paper form", "symmetric": "Part 2, symmetric", "pd": "Part 2, conv.\\ PD"}[mode]
    for name, key, idx, d in (("$\\max|\\varepsilon_2|$", "eps2_max", 1, 3), ("time outside $\\rho_\\omega$ (\\%)", "viol_w", 3, 1),
                              ("time at torque limit (\\%)", "at_limit", 4, 1), ("settling time (s)", "settle", 5, 2),
                              ("torque energy", "energy", 6, 1)):
        mv = mat.get(mkey) if mat else None
        lines.append((lab, name, f(py[key], d), f(mv[idx], d) if mv else "--"))

tex = ["% generated by docs/make_crosscheck.py - do not edit by hand"]
if mat:
    tex.append("\\cref{tab:crosscheck} compares the two implementations metric by metric.")
else:
    tex.append("\\textbf{The MATLAB column is empty because \\code{toy\\_model/run\\_all.m} has not been run on this checkout.} "
               "Run it in MATLAB, then \\code{python3 docs/make\\_crosscheck.py}, and recompile.")
tex += ["\\begin{table}[H]", "\\centering\\small",
        "\\caption{Cross-check: Python (\\code{paper\\_reproduction.py}) vs.\\ MATLAB (\\code{toy\\_model/step6}).}",
        "\\label{tab:crosscheck}", "\\begin{tabular}{@{}llcc@{}}", "\\toprule",
        "\\textbf{Case} & \\textbf{Metric} & \\textbf{Python} & \\textbf{MATLAB}\\\\", "\\midrule"]
prev = None
for case, name, a, b in lines:
    tex.append(f"{case if case != prev else ''} & {name} & {a} & {b}\\\\")
    prev = case
tex += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
if mat:
    diffs = []
    for case, name, a, b in lines:
        try:
            diffs.append(abs(float(a) - float(b)))
        except ValueError:
            pass
    tex.append(f"The largest difference over all {len(diffs)} entries is {max(diffs):.3g} (in the units of the metric).")
open(OUT, "w").write("\n".join(tex) + "\n")
print("wrote", OUT, "(MATLAB log found)" if mat else "(no MATLAB log yet)")
